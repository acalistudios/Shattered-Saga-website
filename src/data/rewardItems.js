export const ATTAINABLE_REWARD_ITEM_LIST = Object.values(ATTAINABLE_REWARD_ITEMS);

export const ATTAINABLE_REWARD_ITEM_BY_NAME = ATTAINABLE_REWARD_ITEM_LIST.reduce((acc, entry) => {
  acc[entry.name] = entry;
  return acc;
}, {});

// Equipment is stored by display name, which can pick up suffixes (quantities,
// condition notes). Prefer an exact match, then fall back to substring so this
// stays consistent with the engine's own `name.includes(...)` effect branches.
export const getRewardItemByName = (itemName) => {
  if (!itemName) return null;
  const nameLower = itemName.toLowerCase();
  return (
    ATTAINABLE_REWARD_ITEM_LIST.find(entry => entry.name.toLowerCase() === nameLower) ||
    ATTAINABLE_REWARD_ITEM_LIST.find(entry => nameLower.includes(entry.name.toLowerCase())) ||
    null
  );
};
